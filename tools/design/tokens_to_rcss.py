#!/usr/bin/env python3
"""Generate game/assets/ui/tokens.rcss from docs/design/tokens.css.

    tools/design/tokens_to_rcss.py docs/design/tokens.css game/assets/ui/tokens.rcss

RmlUi has no custom properties, so the stylesheet cannot read the design
tokens by name. This script turns the locked token block into two things the
client can use:

1. A reference table, as a comment, with every token name and value, so a
   reader of main.rcss can look a literal up in one place.
2. Utility classes for the tokens that are colours, faces and sizes
   (.c-<name> for text colour, .bg-<name> for backgrounds, .f-ui/.f-num/
   .f-display for faces, .fs-<n> for size with its line-height).

main.rcss uses the literal values; a test checks that every token in
tokens.css appears in the committed tokens.rcss, so a token edit without a
regeneration fails CI.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

TOKEN_RE = re.compile(r"^\s*--([a-z0-9-]+)\s*:\s*(.+?)\s*;\s*(?:/\*\s*(.*?)\s*\*/)?\s*$")
HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}$")


def parse(css: str) -> list[tuple[str, str, str]]:
    tokens: list[tuple[str, str, str]] = []
    for line in css.splitlines():
        match = TOKEN_RE.match(line)
        if match:
            tokens.append((match.group(1), match.group(2), match.group(3) or ""))
    return tokens


def font_family(value: str) -> str:
    # "Barlow", system-ui, sans-serif  ->  "Barlow"
    first = value.split(",", 1)[0].strip()
    return first if first.startswith('"') else f'"{first}"'


def render(tokens: list[tuple[str, str, str]]) -> str:
    out: list[str] = []
    out.append("/* GENERATED by tools/design/tokens_to_rcss.py from docs/design/tokens.css.")
    out.append("   Do not edit; change the tokens and regenerate. Values are literal in")
    out.append("   main.rcss because RmlUi has no custom properties; this file is the")
    out.append("   lookup table plus a few utility classes.")
    out.append("")
    width = max(len(name) for name, _, _ in tokens)
    for name, value, note in tokens:
        comment = f"  ({note})" if note else ""
        out.append(f"   --{name:<{width}}  {value}{comment}")
    out.append("*/")
    out.append("")
    sizes: dict[str, str] = {}
    heights: dict[str, str] = {}
    for name, value, _ in tokens:
        if HEX_RE.match(value):
            out.append(f".c-{name} {{ color: {value}; }}")
            out.append(f".bg-{name} {{ background-color: {value}; }}")
        elif name.startswith("font-"):
            face = name.removeprefix("font-")
            out.append(f".f-{face} {{ font-family: {font_family(value)}; }}")
        elif name.startswith("fs-") and value.endswith("px"):
            sizes[name.removeprefix("fs-")] = value.removesuffix("px")
        elif name.startswith("lh-") and value.endswith("px"):
            heights[name.removeprefix("lh-")] = value.removesuffix("px")
    for size, px in sizes.items():
        line_height = heights.get(size, px)
        out.append(f".fs-{size} {{ font-size: {px}dp; line-height: {line_height}dp; }}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    source, target = Path(argv[1]), Path(argv[2])
    tokens = parse(source.read_text(encoding="utf-8"))
    if not tokens:
        print(f"no tokens found in {source}", file=sys.stderr)
        return 1
    target.write_text(render(tokens), encoding="utf-8")
    print(f"{len(tokens)} tokens written to {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
